from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Callable
from urllib import error, request


Transport = Callable[[str, bytes, dict[str, str], int], dict[str, Any]]


class CodeRepairService:
    def __init__(self, settings_service, audit_service, transport: Transport | None = None) -> None:
        self.settings_service = settings_service
        self.audit_service = audit_service
        self.transport = transport or self._default_transport

    def repair_python_file(self, *, path: Path, content: str, validation: dict[str, Any]) -> dict[str, Any] | None:
        settings = self.settings_service.get_all()
        if not settings.get("provider_enabled"):
            return None
        if settings.get("provider_type") != "ollama":
            return None
        model_name = settings.get("ollama_coding_model") or settings.get("model_name")
        base_url = settings.get("model_base_url")
        if not model_name or not base_url:
            return None

        payload = {
            "model": model_name,
            "messages": [
                {"role": "system", "content": self._system_prompt()},
                {
                    "role": "user",
                    "content": self._user_prompt(
                        path=path,
                        content=content,
                        validation=validation,
                    ),
                },
            ],
            "stream": False,
            "think": False,
        }
        raw = self.transport(
            str(base_url),
            json.dumps(payload).encode("utf-8"),
            {"Content-Type": "application/json"},
            max(int(settings.get("provider_timeout_seconds", 120)), 120),
        )
        text = self._extract_ollama_text(raw)
        repaired = self._extract_code(text)
        self.audit_service.log(
            action_type="artifact_repair_attempt",
            action_tier=0,
            tool_name="code_repair_service",
            outcome="completed",
            metadata={"path": str(path), "model_name": model_name},
        )
        return {
            "content": repaired,
            "model_name": model_name,
        }

    def _system_prompt(self) -> str:
        return (
            "You repair invalid Python files generated by an AI agent. "
            "Return only the corrected full file contents with no markdown fences or explanation. "
            "Preserve the intended behavior, prefer pathlib for filesystem paths, "
            "avoid raw Windows backslashes in string literals, replace unresolved placeholders like {workspace_root} "
            "with runnable pathlib-based expressions, and ensure the file compiles cleanly."
        )

    def _user_prompt(self, *, path: Path, content: str, validation: dict[str, Any]) -> str:
        return (
            f"File path: {path.name}\n"
            f"Validation error: {validation.get('message', 'unknown error')}\n"
            f"Line: {validation.get('line', 'unknown')}\n"
            f"Offset: {validation.get('offset', 'unknown')}\n"
            f"Error text: {validation.get('text', '')}\n\n"
            "Repair this file so it compiles and still performs the requested task.\n"
            "Return only the corrected file contents.\n\n"
            "Original file:\n"
            f"{content}"
        )

    def _extract_ollama_text(self, response_payload: dict[str, Any]) -> str:
        message = response_payload.get("message") or {}
        content = message.get("content")
        if isinstance(content, str):
            return content
        if isinstance(response_payload.get("response"), str):
            return response_payload["response"]
        raise ValueError("No model text found in Ollama response")

    def _extract_code(self, text: str) -> str:
        fence_match = re.search(r"```(?:python)?\s*(.*?)```", text, flags=re.DOTALL | re.IGNORECASE)
        if fence_match:
            return fence_match.group(1).strip()
        return text.strip()

    def _default_transport(self, url: str, body: bytes, headers: dict[str, str], timeout_seconds: int) -> dict[str, Any]:
        req = request.Request(url, data=body, headers=headers, method="POST")
        try:
            with request.urlopen(req, timeout=timeout_seconds) as response:
                return json.loads(response.read().decode("utf-8"))
        except error.HTTPError as exc:
            details = exc.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"Provider request failed: {exc.code} {details}") from exc
